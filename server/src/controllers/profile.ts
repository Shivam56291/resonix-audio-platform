export const getPlaylistAudios: RequestHandler = async (req, res) => {
  const { playlistId } = req.params;
  const { pageNo = "0", limit = "20" } = req.query as paginationQuery;

  if (!isValidObjectId(playlistId))
    return res.status(422).json({ error: "Invalid playlist ID" });

  const aggregationLogic = [
    {
      $match: {
        _id: new Types.ObjectId(playlistId),
        $or: [
          { visibility: { $exists: false } },
          { visibility: { $ne: "private" } },
        ],
      },
    },
    {
      $project: {
        items: {
          $slice: [
            "$items",
            parseInt(pageNo) * parseInt(limit),
            parseInt(limit),
          ],
        },
        title: "$title",
        owner: "$owner",
      },
    },
    {
      $unwind: "$items",
    },
    {
      $lookup: {
        from: "audios",
        localField: "items",
        foreignField: "_id",
        as: "audioInfo",
      },
    },
    {
      $unwind: "$audioInfo",
    },
    {
      $lookup: {
        from: "users",
        localField: "owner",
        foreignField: "_id",
        as: "userInfo",
      },
    },
    {
      $unwind: "$userInfo",
    },
    {
      $group: {
        _id: {
          id: "$_id",
          title: "$title",
        },
        audios: {
          $push: {
            id: "$audioInfo._id",
            title: "$audioInfo.title",
            about: "$audioInfo.about",
            category: "$audioInfo.category",
            file: "$audioInfo.file.url",
            poster: { $ifNull: ["$audioInfo.poster.url", null] },
            owner: { name: "$userInfo.name", id: "$userInfo._id" },
          },
        },
      },
    },
    {
      $project: {
        _id: 0,
        id: "$_id.id",
        title: "$_id.title",
        audios: "$$ROOT.audios",
      },
    },
  ];

  const [playlistResult] = await Playlist.aggregate(aggregationLogic);

  if (playlistResult) {
    return res.status(200).json({ list: playlistResult });
  }

  const [autoPlaylistResult] =
    await AutoGeneratedPlaylist.aggregate(aggregationLogic);

  if (autoPlaylistResult) {
    return res.status(200).json({ list: autoPlaylistResult });
  }

  return res.status(404).json({ error: "Playlist not found" });
};

