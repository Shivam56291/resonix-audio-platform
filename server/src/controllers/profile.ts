export const getRecommendByProfile: RequestHandler = async (req, res) => {
  const user = req.user;

  let matchOptions: PipelineStage.Match = {
    $match: { _id: { $exists: true } },
  };

  if (user) {
    const categories = await getUsersPreviousHistory(req);

    if (categories.length > 0) {
      matchOptions = { $match: { category: { $in: categories } } };
    }
  }

  // otherwise we will send generic audios
  const audios = await Audio.aggregate([
    matchOptions,
    {
      $sort: {
        "likes.count": -1,
      },
    },
    { $limit: 10 },
    {
      $lookup: {
        from: "users",
        localField: "owner",
        foreignField: "_id",
        as: "owner",
      },
    },
    { $unwind: "$owner" },
    {
      $project: {
        _id: 0,
        id: "$_id",
        title: "$title",
        category: "$category",
        about: "$about",
        file: "$file.url",
        poster: "$poster.url",
        owner: { name: "$owner.name", id: "$owner._id" },
      },
    },
  ]);

  res.json({ audios });
};

export const getAutoGeneratedPlaylist: RequestHandler = async (req, res) => {
  // 1️⃣ Create Mix 20 playlist from last 20 audios
  const [result] = await History.aggregate([
    { $match: { owner: new Types.ObjectId(req.user.id) } },
    { $unwind: "$all" },
    { $group: { _id: "$all.audio", items: { $addToSet: "$all.audio" } } },
    { $sample: { size: 20 } },
    { $group: { _id: null, items: { $push: "$_id" } } },
  ]);

  const mixTitle = "Mix 20";

  if (result) {
    await Playlist.updateOne(
      { owner: req.user.id, title: mixTitle },
      { $set: { title: mixTitle, items: result.items, visibility: "auto" } },
      { upsert: true },
    );
  }

  // 2️⃣ Fetch user’s recently listened categories
  const categories = await getUsersPreviousHistory(req);

  // 3️⃣ Fetch 4 random AutoGeneratedPlaylists (ignore categories for now)
  const agpl = await AutoGeneratedPlaylist.aggregate([
    { $sample: { size: 4 } },
    {
      $project: {
        _id: 0,
        id: "$_id",
        title: "$title",
        itemsCount: { $size: "$items" },
      },
    },
  ]);

  // 4️⃣ Fetch Mix 20 playlist document
  const mixPlaylist = await Playlist.findOne({
    owner: req.user.id,
    title: mixTitle,
  });

  // 5️⃣ Combine auto playlists + Mix 20
  const finalList = [
    ...agpl,
    {
      id: mixPlaylist?._id,
      title: mixPlaylist?.title,
      itemsCount: mixPlaylist?.items.length ?? 0,
    },
  ];

  res.json({ playlist: finalList });
};

export const getFollowersProfile: RequestHandler = async (req, res) => {
  const { pageNo = "0", limit = "20" } = req.query as paginationQuery;

  const [data] = await User.aggregate([
    { $match: { _id: new Types.ObjectId(req.user.id) } },
    {
      $project: {
        followers: {
          $slice: [
            "$followers",
            parseInt(pageNo) * parseInt(limit),
            parseInt(limit),
          ],
        },
      },
    },
    {
      $unwind: "$followers",
    },
    {
      $lookup: {
        from: "users",
        localField: "followers",
        foreignField: "_id",
        as: "userInfo",
      },
    },
    {
      $unwind: "$userInfo",
    },
    {
      $group: {
        _id: null,
        followers: {
          $push: {
            id: "$userInfo._id",
            name: "$userInfo.name",
            avatar: "$userInfo.avatar?.url",
          },
        },
      },
    },
  ]);

  if (!data) return res.status(404).json({ followers: [] });

  res.status(201).json({ followers: data.followers });
};

